-- 装机研究所 | PostgreSQL 18 初始化脚本（UTF-8）
-- 在 pgAdmin 中右键已有的 RIGLAB 数据库，打开 Query Tool，载入并执行整个文件。
-- 项目表放在 riglab schema，与 public 下的练习表分开。
-- 可重复运行初始化。表结构调整请另写迁移脚本。
 BEGIN;

DO $$
BEGIN
    IF lower(current_database()) <> 'riglab' THEN
        RAISE EXCEPTION '请切换到 RIGLAB 数据库后执行。当前数据库：%', current_database();
    END IF;
END;
$$;


CREATE SCHEMA IF NOT EXISTS riglab;

-- 分类代码与现有前端一致，如 cpu、gpu、board。

CREATE TABLE IF NOT EXISTS riglab.categories (code text PRIMARY KEY,
                                                        name text NOT NULL UNIQUE,
                                                                           english_name text NOT NULL,
                                                                                             icon text NOT NULL,
                                                                                                       description text NOT NULL,
                                                                                                                        sort_order smallint NOT NULL UNIQUE CHECK (sort_order > 0));


CREATE TABLE IF NOT EXISTS riglab.parts (-- 保留前端自带型号的编号，便于以后接入现有推荐方案。
 id bigint GENERATED BY DEFAULT AS IDENTITY
                                             (START WITH 1000) PRIMARY KEY,
                                                               category text NOT NULL REFERENCES riglab.categories (code),
                                                                                                 name varchar(100) NOT NULL CHECK (btrim(name) <> ''), brand varchar(40) NOT NULL CHECK (btrim(brand) <> ''), price numeric(10, 2) NOT NULL CHECK (price BETWEEN 0.01 AND 999999), spec varchar(200) NOT NULL CHECK (btrim(spec) <> ''), status text NOT NULL DEFAULT 'active' CHECK (status IN ('active',
                                                                                                                                                                                                                                                                                                                                                                                                 'inactive')), socket text, ddr text, power integer CHECK (power > 0), watts integer CHECK (watts > 0), tag text, chip text, created_at timestamptz NOT NULL DEFAULT now(),
                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                     UNIQUE (id,
                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                                             category));


ALTER TABLE riglab.parts ADD COLUMN IF NOT EXISTS purchase_url text;
ALTER TABLE riglab.parts ADD COLUMN IF NOT EXISTS purchase_kind text DEFAULT 'search';

CREATE UNIQUE INDEX IF NOT EXISTS parts_model_unique ON riglab.parts (category, lower(brand), lower(name));

-- 账号由后端注册或创建。后端写入密码哈希，管理员角色由受信任的后端流程分配。

CREATE TABLE IF NOT EXISTS riglab.users (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                                                                                username varchar(64) NOT NULL CHECK (btrim(username) <> ''), nickname varchar(20) NOT NULL CHECK (btrim(nickname) <> ''), password_hash text NOT NULL CHECK (btrim(password_hash) <> ''), role text NOT NULL DEFAULT 'user' CHECK (role IN ('user',
                                                                                                                                                                                                                                                                                                                            'admin')), created_at timestamptz NOT NULL DEFAULT now());


CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique ON riglab.users (lower(username));

-- 用户自建配置默认为私有。社区接口只读取 public 配置。

CREATE TABLE IF NOT EXISTS riglab.builds
    (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                                            user_id bigint NOT NULL REFERENCES riglab.users (id) ON DELETE CASCADE,
                                                                                                           name text NOT NULL CHECK (btrim(name) <> ''), budget numeric(12, 2) CHECK (budget >= 0), visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private',
                                                                                                                                                                                                                                                                     'public')), tag text, theme text, created_at timestamptz NOT NULL DEFAULT now());


CREATE INDEX IF NOT EXISTS builds_user_idx ON riglab.builds (user_id);


CREATE INDEX IF NOT EXISTS builds_public_idx ON riglab.builds (created_at DESC, id DESC)
WHERE visibility = 'public';

-- 一套配置的同一分类只能选一个型号，且型号必须属于该分类。

CREATE TABLE IF NOT EXISTS riglab.build_parts
    (build_id bigint NOT NULL REFERENCES riglab.builds (id) ON DELETE CASCADE,
                                                                      category text NOT NULL,
                                                                                    part_id bigint NOT NULL,
                                                                                                   PRIMARY KEY (build_id,
                                                                                                                category),
     FOREIGN KEY (part_id,
                  category) REFERENCES riglab.parts (id, category));


CREATE INDEX IF NOT EXISTS build_parts_part_idx ON riglab.build_parts (part_id, category);


CREATE TABLE IF NOT EXISTS riglab.favorites
    (user_id bigint NOT NULL REFERENCES riglab.users (id) ON DELETE CASCADE,
                                                                    build_id bigint NOT NULL REFERENCES riglab.builds (id) ON DELETE CASCADE,
                                                                                                                                     created_at timestamptz NOT NULL DEFAULT now(),
                                                                                                                                                                             PRIMARY KEY (user_id,
                                                                                                                                                                                          build_id));


CREATE INDEX IF NOT EXISTS favorites_build_idx ON riglab.favorites (build_id);


CREATE TABLE IF NOT EXISTS riglab.page_visits (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                                                                                      visitor text NOT NULL,
                                                                                                   page text NOT NULL,
                                                                                                             device text NOT NULL,
                                                                                                                         source text NOT NULL,
                                                                                                                                     occurred_at timestamptz NOT NULL DEFAULT now());


CREATE INDEX IF NOT EXISTS page_visits_time_idx ON riglab.page_visits (occurred_at DESC);

-- 每次加入配件产生一条记录。统计的是选配次数。

CREATE TABLE IF NOT EXISTS riglab.part_selections (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                                                                                          part_id bigint NOT NULL REFERENCES riglab.parts (id),
                                                                                                                             visitor text NOT NULL,
                                                                                                                                          occurred_at timestamptz NOT NULL DEFAULT now());


CREATE INDEX IF NOT EXISTS part_selections_part_time_idx ON riglab.part_selections (part_id, occurred_at DESC);


CREATE INDEX IF NOT EXISTS part_selections_time_idx ON riglab.part_selections (occurred_at DESC);

